function ledoitWolfShrinkage(nFeatures: number, S: Float64Array): number {
  let trS = 0;
  let trS2 = 0;
  for (let i = 0; i < nFeatures; i++) {
    trS += S[i * nFeatures + i] ?? 0;
    for (let j = 0; j < nFeatures; j++) {
      const v = S[i * nFeatures + j] ?? 0;
      trS2 += v * v;
    }
  }

  const rhoNum = (1 - 2 / nFeatures) * trS2 + trS * trS;
  const rhoDen = (nFeatures + 1 - 2 / nFeatures) * (trS2 - (trS * trS) / nFeatures);

  if (Math.abs(rhoDen) < 1e-15) return 1;
  return Math.max(0, Math.min(1, rhoNum / rhoDen));
}

function topEigenvectors(
  M: Float64Array,
  n: number,
  k: number
): { vectors: Float64Array; values: number[] } {
  const vectors = new Float64Array(n * k);
  const values: number[] = [];
  const Mcopy = new Float64Array(M);

  for (let idx = 0; idx < k; idx++) {
    const v = new Float64Array(n);
    for (let i = 0; i < n; i++) {
      v[i] = (i === idx ? 1 : 0) + 0.01 * Math.sin(i * 7 + idx * 13);
    }

    let eigenvalue = 0;
    for (let iter = 0; iter < 300; iter++) {
      const Mv = new Float64Array(n);
      for (let i = 0; i < n; i++) {
        let sum = 0;
        for (let j = 0; j < n; j++) {
          sum += (Mcopy[i * n + j] ?? 0) * (v[j] ?? 0);
        }
        Mv[i] = sum;
      }

      let norm = 0;
      for (let i = 0; i < n; i++) {
        norm += (Mv[i] ?? 0) * (Mv[i] ?? 0);
      }
      norm = Math.sqrt(norm);
      if (norm < 1e-15) break;

      eigenvalue = norm;
      let dot = 0;
      for (let i = 0; i < n; i++) {
        dot += (Mv[i] ?? 0) * (v[i] ?? 0);
      }
      if (dot < 0) eigenvalue = -eigenvalue;

      for (let i = 0; i < n; i++) {
        v[i] = (Mv[i] ?? 0) / norm;
      }
    }

    values.push(Math.abs(eigenvalue));
    for (let i = 0; i < n; i++) {
      vectors[i * k + idx] = v[i] ?? 0;
    }

    // Deflate
    for (let i = 0; i < n; i++) {
      for (let j = 0; j < n; j++) {
        Mcopy[i * n + j] = (Mcopy[i * n + j] ?? 0) - eigenvalue * (v[i] ?? 0) * (v[j] ?? 0);
      }
    }
  }

  return { vectors, values };
}
