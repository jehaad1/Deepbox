describe("wave3 autograd: multi-axis reductions", () => {
  const axesOf: Record<string, number[]> = {
    "02": [0, 2],
    m1m2k: [-1, -2],
    all3: [0, 1, 2],
    all3k: [0, 1, 2],
    single: [1],
  };
  const keepOf: Record<string, boolean> = {
    "02": false,
    m1m2k: true,
    all3: false,
    all3k: true,
    single: false,
  };
  for (const key of Object.keys(axesOf)) {
    const axes = axesOf[key] as number[];
    const kd = keepOf[key] as boolean;
    it(`sum / mean / max / min over [${axes}] keepdims=${kd} match torch`, () => {
      check(pick(REF.multi, `sum_${key}`), (g) => g.sum(axes, kd));
      check(pick(REF.multi, `mean_${key}`), (g) => g.mean(axes, kd));
      check(pick(REF.multi, `max_${key}`), (g) => g.max(axes, kd));
      check(pick(REF.multi, `min_${key}`), (g) => g.min(axes, kd));
    });
  }

  it("max over several axes propagates NaN and sends the gradient to the NaN element", () => {
    const c = pick(REF.multi, "max_nan");
    const x = leaf(c.x, c.shape);
    const y = x.max([0, 2]);
    expectClose(values(y), c.out);
    y.sum().backward();
    const grad = values(x.grad as Tensor);
    const nanIndex = c.x.findIndex((v) => Number.isNaN(v));
    expect(grad[nanIndex]).toBe(1);
    expect(grad.reduce((p, q) => p + q, 0)).toBe(c.shape[1] as number);
  });

  it("works on non-contiguous views", () => {
    check(pick(REF.strided, "max"), (g) => g.transpose().max([0, 1]));
    check(pick(REF.strided, "sum"), (g) => g.transpose().sum([0, 1]));
  });

  it("splits the gradient equally between tied maxima over several axes", () => {
    const x = parameter([
      [1, 3],
      [3, 0],
    ]);
    x.max([0, 1]).backward();
    expect(values(x.grad as Tensor)).toEqual([0, 0.5, 0.5, 0]);
  });

  it("a single-element axis list equals the plain axis", () => {
    const x = leaf([1, 2, 3, 4, 5, 6], [2, 3]);
    expect(values(x.sum([1]))).toEqual(values(x.sum(1)));
    expect(values(x.mean([-1], true))).toEqual(values(x.mean(-1, true)));
    expect(values(x.max([0]))).toEqual(values(x.max(0)));
    expect(values(x.min([0], true))).toEqual(values(x.min(0, true)));
  });

  it("an empty axis list reduces nothing", () => {
    const x = leaf([1, 2, 3, 4], [2, 2]);
    const y = x.sum([]);
    expect(y.shape).toEqual([2, 2]);
    y.sum().backward();
    expect(values(x.grad as Tensor)).toEqual([1, 1, 1, 1]);
  });

  it("rejects duplicate and out-of-range axes", () => {
    const x = leaf([1, 2, 3, 4], [2, 2]);
    expect(() => x.sum([0, 0])).toThrow(InvalidParameterError);
    expect(() => x.mean([0, -2])).toThrow(InvalidParameterError);
    expect(() => x.max([0, 2])).toThrow(InvalidParameterError);
    expect(() => x.min([5])).toThrow(InvalidParameterError);
  });

  it("keeps float32 dtype and mean divides by the product of the reduced sizes", () => {
    const x = leaf([1, 2, 3, 4, 5, 6, 7, 8], [2, 2, 2], "float32");
    const m = x.mean([0, 2]);
    expect(m.dtype).toBe("float32");
    expect(values(m)).toEqual([3.5, 5.5]);
    m.sum().backward();
    expect(values(x.grad as Tensor)).toEqual(new Array(8).fill(0.25));
    expect(x.grad?.dtype).toBe("float32");
  });

  it("handles 0-d input and empty axis lists", () => {
    const s = GradTensor.scalar(2, { dtype: "float64", requiresGrad: true });
    const y = s.sum([]);
    expect(y.shape).toEqual([]);
    y.backward();
    expect(values(s.grad as Tensor)).toEqual([1]);
    check(pick(REF.zeroD, "sum"), (g) => g.sum());
  });
});

describe("wave3 autograd: requiresGrad inside noGrad", () => {
  it("parameter keeps requiresGrad inside noGrad", () => {
    const p = noGrad(() => parameter([1, 2, 3]));
    expect(p.requiresGrad).toBe(true);
    p.sum().backward();
    expect(values(p.grad as Tensor)).toEqual([1, 1, 1]);
  });

  it("fromTensor and the constructor keep the requested flag", () => {
    const t = tensor([1, 2]);
    const a = noGrad(() => GradTensor.fromTensor(t, { requiresGrad: true }));
    expect(a.requiresGrad).toBe(true);
    const b = noGrad(() => GradTensor.fromTensor(t));
    expect(b.requiresGrad).toBe(false);
    const c = noGrad(() => new GradTensor([1, 2], { requiresGrad: true }));
    expect(c.requiresGrad).toBe(true);
    const d = noGrad(() => GradTensor.scalar(1, { requiresGrad: true }));
    expect(d.requiresGrad).toBe(true);
  });

  it("setRequiresGrad works inside noGrad", () => {
    const x = GradTensor.fromTensor(tensor([1, 2]));
    noGrad(() => x.setRequiresGrad(true));
    expect(x.requiresGrad).toBe(true);
  });

  it("operations inside noGrad still do not record a graph", () => {
    const p = parameter([1, 2, 3]);
    const q = noGrad(() => {
      const fresh = parameter([4, 5, 6]);
      return { sum: p.add(fresh), sin: fresh.sin(), max: fresh.max([0]), cum: fresh.cumsum() };
    });
    expect(q.sum.requiresGrad).toBe(false);
    expect(q.sin.requiresGrad).toBe(false);
    expect(q.max.requiresGrad).toBe(false);
    expect(q.cum.requiresGrad).toBe(false);
  });

  it("gradient tracking is restored after noGrad and after an exception", () => {
    expect(() =>
      noGrad(() => {
        throw new Error("boom");
      })
    ).toThrow("boom");
    const x = parameter([1, 2]);
    expect(x.mul(x).requiresGrad).toBe(true);
  });

  it("a leaf made inside noGrad can be used for training afterwards", () => {
    const w = noGrad(() => parameter([2, 3]));
    const loss = w.mul(w).sum();
    expect(loss.requiresGrad).toBe(true);
    loss.backward();
    expect(values(w.grad as Tensor)).toEqual([4, 6]);
  });
});
