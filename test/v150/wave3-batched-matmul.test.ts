function flatten(v: unknown): unknown[] {
  if (Array.isArray(v)) return v.flatMap(flatten);
  return [v];
}

function nums(t: Tensor | GradTensor): number[] {
  return flatten(t.toArray()).map((x) => (typeof x === "bigint" ? Number(x) : (x as number)));
}

function expectClose(actual: readonly number[], expected: readonly number[], tol = 1e-9): void {
  expect(actual.length).toBe(expected.length);
  for (let i = 0; i < expected.length; i++) {
    const a = actual[i] as number;
    const e = expected[i] as number;
    if (Number.isNaN(e)) {
      expect(a, `index ${i}`).toBeNaN();
    } else if (!Number.isFinite(e)) {
      expect(a, `index ${i}`).toBe(e);
    } else {
      expect(Math.abs(a - e), `index ${i}: ${a} vs ${e}`).toBeLessThanOrEqual(
        tol * Math.max(1, Math.abs(e))
      );
    }
  }
}

function ar(n: number, map: (i: number) => number = (i) => i): number[] {
  return Array.from({ length: n }, (_, i) => map(i));
}

function expectExtra(t: Tensor, ref: ExtraRef | undefined): void {
  if (ref === undefined) throw new Error("missing reference");
  expect(t.shape).toEqual(ref.shape);
  expectClose(
    nums(t),
    ref.v.map((x) => Number(x)),
    1e-12
  );
}

function view(
  data: number[],
  shape: number[],
  strides: number[],
  offset = 0,
  dtype: "float64" | "float32" = "float64"
): Tensor {
  return TensorClass.fromTypedArray({
    data: dtype === "float64" ? new Float64Array(data) : new Float32Array(data),
    shape,
    dtype,
    device: "cpu",
    strides,
    offset,
  });
}

