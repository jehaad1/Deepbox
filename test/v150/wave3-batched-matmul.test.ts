/** Minimal in-memory kernel backend: only transfer and matmul kernels are real. */
type MiniBuffer = DeviceBuffer & { data: Float32Array };

class MiniBackend {
  matmulCalls = 0;
  batchedCalls = 0;
  lastBatched: { aLayout: KernelLayout; bLayout: KernelLayout } | null = null;

  info(): BackendInfo {
    return { device: "webgpu", name: "Mini", available: true, capabilities: ["matmul"] };
  }
  supports(cap: BackendCapability): boolean {
    return cap === "matmul";
  }
  async init(): Promise<void> {}
  dispose(): void {}

  private wrap(data: Float32Array): MiniBuffer {
    return {
      device: "webgpu",
      byteLength: data.length * 4,
      size: data.length,
      dtype: "float32" as DeviceDType,
      data,
    };
  }
  private gather(buffer: DeviceBuffer, layout: KernelLayout): Float32Array {
    const buf = buffer as MiniBuffer;
    const size = layout.shape.reduce((x, y) => x * y, 1);
    const out = new Float32Array(size);
    for (let i = 0; i < size; i++) {
      let rem = i;
      let idx = layout.offset;
      for (let d = layout.shape.length - 1; d >= 0; d--) {
        const dim = layout.shape[d] ?? 1;
        idx += (rem % dim) * (layout.strides[d] ?? 0);
        rem = Math.floor(rem / dim);
      }
      out[i] = buf.data[idx] ?? 0;
    }
    return out;
  }
  upload(data: Float32Array): DeviceBuffer {
    return this.wrap(data.slice());
  }
  async download(buffer: DeviceBuffer): Promise<Float32Array> {
    return (buffer as MiniBuffer).data.slice();
  }
  free(): void {}
  matmul(
    a: DeviceBuffer,
    aLayout: KernelLayout,
    b: DeviceBuffer,
    bLayout: KernelLayout
  ): DeviceBuffer {
    this.matmulCalls++;
    const m = aLayout.shape[0] ?? 0;
    const k = aLayout.shape[1] ?? 0;
    const n = bLayout.shape[1] ?? 0;
    return this.wrap(this.product(this.gather(a, aLayout), this.gather(b, bLayout), 1, m, k, n));
  }
  matmulBatched(
    a: DeviceBuffer,
    aLayout: KernelLayout,
    b: DeviceBuffer,
    bLayout: KernelLayout,
    batch: number,
    m: number,
    k: number,
    n: number
  ): DeviceBuffer {
    this.batchedCalls++;
    this.lastBatched = { aLayout, bLayout };
    return this.wrap(
      this.product(this.gather(a, aLayout), this.gather(b, bLayout), batch, m, k, n)
    );
  }
  private product(
    av: Float32Array,
    bv: Float32Array,
    batch: number,
    m: number,
    k: number,
    n: number
  ): Float32Array {
    const out = new Float32Array(batch * m * n);
    for (let t = 0; t < batch; t++) {
      for (let i = 0; i < m; i++) {
        for (let j = 0; j < n; j++) {
          let acc = 0;
          for (let p = 0; p < k; p++) {
            acc += (av[t * m * k + i * k + p] ?? 0) * (bv[t * k * n + p * n + j] ?? 0);
          }
          out[t * m * n + i * n + j] = acc;
        }
      }
    }
    return out;
  }
}

describe("dot on a kernel device broadcasts batch dimensions", () => {
  const mini = new MiniBackend();
  const unsupported = (name: string) => () => {
    throw new DeviceError(`mini backend: ${name} is not implemented`);
  };
  for (const name of [
    "fill",
    "binary",
    "unary",
    "reduce",
    "reduceAxis",
    "ternary",
    "im2col",
    "col2im",
    "pool2d",
    "pool2dBackward",
  ]) {
    Object.defineProperty(mini, name, { value: unsupported(name) });
  }
  beforeAll(() => {
    registerBackend("webgpu", mini as unknown as Backend & KernelBackend);
  });
  afterAll(() => {
    resetConfig();
  });

  const hostResult = (sa: number[], sb: number[]) => {
    const a = tensor(
      ar(
        sa.reduce((x, y) => x * y, 1),
        (i) => ((i * 7) % 11) - 5
      ),
      {
        dtype: "float32",
      }
    ).reshape(sa);
    const b = tensor(
      ar(
        sb.reduce((x, y) => x * y, 1),
        (i) => ((i * 5) % 13) - 6
      ),
      {
        dtype: "float32",
      }
    ).reshape(sb);
    return { a, b, expected: dot(a, b) };
  };

  const shapes: [number[], number[]][] = [
    [
      [1, 2, 3],
      [3, 3, 4],
    ],
    [
      [3, 2, 3],
      [1, 3, 4],
    ],
    [
      [2, 1, 2, 3],
      [3, 3, 2],
    ],
    [
      [4, 2, 3],
      [3, 2],
    ],
    [
      [2, 3],
      [4, 3, 2],
    ],
    [[3], [2, 3, 4]],
    [[2, 3, 2, 3], [3]],
    [
      [2, 2],
      [2, 2],
    ],
  ];
  for (const [sa, sb] of shapes) {
    it(`[${sa}] @ [${sb}] matches the CPU result`, async () => {
      const { a, b, expected } = hostResult(sa, sb);
      const ad = await a.to("webgpu");
      const bd = await b.to("webgpu");
      const out = dot(ad, bd);
      expect(out.device).toBe("webgpu");
      expect(out.shape).toEqual(expected.shape);
      const back = await out.cpu();
      expectClose(nums(back), nums(expected), 1e-6);
    });
  }

  it("uses the batched kernel with stride-0 layouts for broadcast batch dimensions", async () => {
    const a = tensor(ar(12), { dtype: "float32" }).reshape([1, 2, 6]);
    const b = tensor(ar(36), { dtype: "float32" }).reshape([3, 6, 2]);
    mini.batchedCalls = 0;
    const out = dot(await a.to("webgpu"), await b.to("webgpu"));
    expect(mini.batchedCalls).toBe(1);
    expect(mini.lastBatched?.aLayout.strides[0]).toBe(0);
    expect(mini.lastBatched?.bLayout.strides[0]).toBe(12);
    expect(out.shape).toEqual([3, 2, 2]);
  });

  it("plain vector and matrix products still use the 2-D kernel", async () => {
    mini.matmulCalls = 0;
    mini.batchedCalls = 0;
    const out = dot(
      await tensor([1, 2, 3], { dtype: "float32" }).to("webgpu"),
      await tensor([4, 5, 6], { dtype: "float32" }).to("webgpu")
    );
    expect(mini.matmulCalls).toBe(1);
    expect(mini.batchedCalls).toBe(0);
    expect(out.shape).toEqual([]);
  });

  it("reports the same shape errors as the CPU", async () => {
    const x = await tensor(ar(12), { dtype: "float32" }).reshape([2, 2, 3]).to("webgpu");
    const y = await tensor(ar(36), { dtype: "float32" }).reshape([3, 3, 4]).to("webgpu");
    expect(() => dot(x, y)).toThrow(/batch dimensions/);
    const z = await tensor(ar(40), { dtype: "float32" }).reshape([2, 4, 5]).to("webgpu");
    expect(() => dot(x, z)).toThrow(/not aligned/);
    const s = await tensor(2, { dtype: "float32" }).to("webgpu");
    expect(() => dot(s, x)).toThrow(/0-d/);
    const cpu = tensor(ar(12), { dtype: "float32" }).reshape([2, 3, 2]);
    expect(() => dot(x, cpu)).toThrow(DeviceError);
  });
});
