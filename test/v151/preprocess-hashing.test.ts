class Lcg {
  private x: number;
  constructor(seed: number) {
    this.x = seed;
  }
  below(n: number): number {
    this.x = (this.x * 48271) % 2147483647;
    return this.x % n;
  }
}

function buildDocs(i: number): { config: Config; configIndex: number; docs: string[] } {
  const rng = new Lcg(1000 + i);
  const configIndex = rng.below(CONFIGS.length);
  const nDocs = 1 + rng.below(3);
  const docs: string[] = [];
  for (let d = 0; d < nDocs; d++) {
    const nWords = 3 + rng.below(10);
    let s = "";
    for (let w = 0; w < nWords; w++) {
      s += (VOCAB[rng.below(VOCAB.length)] as string) + (PUNCT[rng.below(PUNCT.length)] as string);
    }
    docs.push(s);
  }
  return { config: CONFIGS[configIndex] as Config, configIndex, docs };
}

/** Row norm of `values` as sklearn's normalize computes it; 1 when the row is all zero. */
function rowNorm(values: number[], norm: "l1" | "l2" | null): number {
  if (norm === null) return 1;
  const total =
    norm === "l1"
      ? values.reduce((acc, v) => acc + Math.abs(v), 0)
      : Math.sqrt(values.reduce((acc, v) => acc + v * v, 0));
  return total === 0 ? 1 : total;
}

describe("HashingVectorizer matches scikit-learn", () => {
  it("reproduces the corpora of the reference", () => {
    for (const [i, [configIndex]] of EXPECTED.entries()) {
      expect(buildDocs(i).configIndex).toBe(configIndex);
    }
  });

  it("gives the same columns and values on 200 random corpora", () => {
    for (const [i, [, rows]] of EXPECTED.entries()) {
      const { config, docs } = buildDocs(i);
      const hv = new HashingVectorizer({
        nFeatures: config.nf,
        alternateSign: config.alt,
        norm: config.norm === null ? undefined : config.norm,
        binary: config.binary,
        ngramRange: config.ng,
      });
      const dense = hv.transformText(docs).toArray() as number[][];
      expect(dense.length, `corpus ${i}`).toBe(rows.length);
      for (const [r, flat] of rows.entries()) {
        const expected = new Array<number>(config.nf).fill(0);
        const values: number[] = [];
        for (let k = 0; k < flat.length; k += 2) values.push(flat[k + 1] as number);
        const scale = rowNorm(values, config.norm);
        for (let k = 0; k < flat.length; k += 2) {
          expected[flat[k] as number] = (flat[k + 1] as number) / scale;
        }
        const row = dense[r] as number[];
        for (let c = 0; c < config.nf; c++) {
          expect(row[c], `corpus ${i} doc ${r} column ${c}`).toBeCloseTo(expected[c] as number, 6);
        }
      }
    }
  });
});
